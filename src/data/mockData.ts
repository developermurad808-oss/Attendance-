/**
 * Generate calculated payroll list for all staff
 */
export function generatePayrollRecords(staffList: Staff[], month = 'August 2026', year = 2026): PayrollRecord[] {
  return staffList.map(stf => {
    const totalAllowances = Object.values(stf.allowances).reduce((a, b) => a + (b || 0), 0);
    const grossPay = stf.baseSalary + totalAllowances;
    
    // Statutory Pension (8% of Base Salary + Housing + Transport)
    const pensionBase = stf.baseSalary + (stf.allowances.housing || 0) + (stf.allowances.transport || 0);
    const pensionContribution = Math.round(pensionBase * 0.08);

    // Nigerian PAYE approximate effective tax (e.g. ~10% of gross after pension relief)
    const payeTax = Math.round((grossPay - pensionContribution) * 0.10);

    // Dynamic mock attendance variations
    let daysLate = 0;
    let daysAbsentUnexcused = 0;
    let daysOnApprovedLeave = 0;

    if (stf.id === 'stf_04') {
      daysOnApprovedLeave = 3;
    } else if (stf.id === 'stf_07') {
      daysLate = 1;
    } else if (stf.id === 'stf_08') {
      daysLate = 2;
    }

    const workingDaysExpected = 22;
    const daysPresent = workingDaysExpected - daysAbsentUnexcused - daysOnApprovedLeave;

    // Penalty deductions: ₦3,500 per late after 1 grace, ₦15,000 per unexcused absence
    const lateDeductions = Math.max(0, daysLate - 1) * 3500;
    const unexcusedAbsenceDeduction = daysAbsentUnexcused * 15000;

    const totalDeductions = pensionContribution + payeTax + lateDeductions + unexcusedAbsenceDeduction;
    const netPay = grossPay - totalDeductions;

    return {
      id: `pyr_${stf.id}_${year}_08`,
      staffId: stf.id,
      staffName: `${stf.firstName} ${stf.lastName}`,
      employeeId: stf.employeeId,
      role: stf.role,
      department: stf.department,
      month,
      year,
      baseSalary: stf.baseSalary,
      totalAllowances,
      allowancesBreakdown: stf.allowances,
      workingDaysExpected,
      daysPresent,
      daysLate,
      daysAbsentUnexcused,
      daysOnApprovedLeave,
      deductions: {
        lateDeductions,
        unexcusedAbsenceDeduction,
        pensionContribution,
        payeTax,
      },
      totalDeductions,
      grossPay,
      netPay,
      bankName: stf.bankName,
      accountNumber: stf.accountNumber,
      paymentStatus: 'Approved',
      disbursedAt: '2026-08-25',
      payslipSent: true,
    };
  });
}
